# -*- coding: utf-8 -*-
"""把 python/bootstrap.py 转成 C 字节数组头文件。

用字节数组而不是原始字符串字面量：脚本里出现任何引号/反斜杠/非 ASCII
都不会破坏 C++ 语法，也不需要关心转义。
"""
from __future__ import print_function
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, 'python', 'bootstrap.py')
DST = os.path.join(ROOT, 'src', 'embedded_bootstrap.h')
PER_LINE = 20


def main():
    if not os.path.isfile(SRC):
        print('missing: %s' % SRC)
        return 1
    data = open(SRC, 'rb').read()
    if not data:
        print('bootstrap.py is empty')
        return 1
    # 只做提示：py2 的 PyRun_SimpleString 没有 coding cookie，非 ASCII 会炸
    non_ascii = [i for i, b in enumerate(data) if b > 127]
    if non_ascii:
        print('warn: bootstrap.py has %d non-ASCII bytes (py2 may raise SyntaxError)'
              % len(non_ascii))

    lines = []
    lines.append('// generated by tools/embed.py -- do not edit')
    lines.append('#pragma once')
    lines.append('')
    lines.append('static const unsigned char kBootstrap[] = {')
    for i in range(0, len(data), PER_LINE):
        chunk = data[i:i + PER_LINE]
        lines.append('    ' + ','.join('0x%02X' % b for b in chunk) + ',')
    lines.append('};')
    lines.append('')
    lines.append('static const unsigned int kBootstrapLen = %d;' % len(data))
    lines.append('')

    out = '\n'.join(lines)
    with io.open(DST, 'w', encoding='utf-8', newline='\n') as f:
        f.write(out)
    print('wrote %s (%d bytes payload, %d lines)' % (DST, len(data), len(lines)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
